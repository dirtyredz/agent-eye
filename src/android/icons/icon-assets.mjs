// Pure icon library: restricted SVG parsing, VectorDrawable conversion, rendering, output list, drift check.
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import sharp from 'sharp';

export const GENERATED_NOTE = '<!-- Generated by src/android/icons/generate-icons.mjs from agent-eye.svg. Do not edit. -->';
export const SVG_PATH = 'src/android/icons/agent-eye.svg';
export const SAFE_CENTER = [54, 54];
export const SAFE_RADIUS = 33;
const RES = 'android/app/src/main/res';
const NS = 'xmlns:android="http://schemas.android.com/apk/res/android"';
const ROLES = ['background', 'ring', 'iris', 'pupil', 'highlight'];
const DENSITIES = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };

// ---- parsing -------------------------------------------------------------------------------
const ALLOWED_ATTRS = { svg: ['xmlns', 'width', 'height', 'viewBox'], path: ['id', 'd', 'fill', 'fill-rule'] };

export function parseSvg(text) {
  const body = text.replace(/<\?xml[^>]*\?>/g, '').replace(/<!--[\s\S]*?-->/g, '');
  const tagRe = /<(\/?)([^\s/>!?]+)([^>]*)>/g;
  const paths = [];
  let svgSeen = false, closed = false, last = 0, match;
  const stray = chunk => { if (chunk.trim()) throw new Error(`Unsupported SVG: unexpected text "${chunk.trim().slice(0, 20)}"`); };
  while ((match = tagRe.exec(body))) {
    stray(body.slice(last, match.index));
    last = tagRe.lastIndex;
    const [, closing, name, rest] = match;
    if (name !== 'svg' && name !== 'path') throw new Error(`Unsupported SVG element <${name}>; only <svg> and <path> are allowed`);
    if (closing) { if (name === 'svg') closed = true; continue; }
    const attrs = readAttrs(name, rest);
    if (name === 'svg') {
      if (svgSeen) throw new Error('Unsupported SVG: nested <svg>');
      if (attrs.viewBox !== '0 0 108 108') throw new Error(`Unsupported SVG: viewBox must be "0 0 108 108", got "${attrs.viewBox}"`);
      svgSeen = true;
    } else {
      if (!svgSeen) throw new Error('Unsupported SVG: <path> outside <svg>');
      paths.push(validatePath(attrs));
    }
  }
  stray(body.slice(last));
  if (!svgSeen || !closed) throw new Error('Unsupported SVG: missing <svg> root');
  const roles = paths.map(p => p.id);
  if (roles.join() !== ROLES.join()) throw new Error(`SVG paths must be exactly [${ROLES}] in order, got [${roles}]`);
  return Object.fromEntries(paths.map(p => [p.id, p]));
}

function readAttrs(element, rest) {
  const attrs = {};
  const left = rest.replace(/\/\s*$/, '').replace(/([^\s=]+)\s*=\s*"([^"]*)"/g, (_, key, value) => { attrs[key] = value; return ''; });
  if (left.trim()) throw new Error(`Unsupported SVG: malformed attributes on <${element}>: ${left.trim()}`);
  for (const key of Object.keys(attrs)) {
    if (!ALLOWED_ATTRS[element].includes(key)) throw new Error(`Unsupported SVG attribute "${key}" on <${element}> (transform, href, stroke, style, fonts and others are rejected)`);
  }
  return attrs;
}

function validatePath({ id, d, fill, 'fill-rule': rule }) {
  if (!ROLES.includes(id)) throw new Error(`Unsupported SVG path id "${id}"`);
  if (!d || /[^MmLlHhVvCcAaZz0-9eE.,\s+-]/.test(d)) throw new Error(`Path "${id}" has unsupported path data`);
  if (!/^#[0-9A-Fa-f]{6}$/.test(fill ?? '')) throw new Error(`Path "${id}" fill must be #RRGGBB (no url() or named colours), got "${fill}"`);
  if (rule !== 'nonzero' && rule !== 'evenodd') throw new Error(`Path "${id}" fill-rule must be nonzero or evenodd`);
  return { id, d, fill: fill.toUpperCase(), rule };
}

// ---- XML resources -------------------------------------------------------------------------
export function toVectorDrawable(shapes) {
  return [
    GENERATED_NOTE, `<vector ${NS}`, '    android:width="108dp"', '    android:height="108dp"',
    '    android:viewportWidth="108"', '    android:viewportHeight="108">',
    ...shapes.map(s => `    <path android:fillColor="#FF${s.fill.slice(1)}" android:fillType="${s.rule === 'evenodd' ? 'evenOdd' : 'nonZero'}" android:pathData="${s.d}"/>`),
    '</vector>', ''].join('\n');
}

// Single-colour silhouette: ring, plus iris with the pupil punched out as a hole. Highlight omitted.
export function monochromeShapes(p) {
  return [{ ...p.ring, fill: '#FFFFFF' }, { fill: '#FFFFFF', rule: 'evenodd', d: `${p.iris.d} ${p.pupil.d}` }];
}

export function adaptiveXml(monochrome) {
  return [GENERATED_NOTE, `<adaptive-icon ${NS}>`,
    '    <background android:drawable="@drawable/ic_launcher_background"/>',
    '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>',
    ...(monochrome ? ['    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>'] : []),
    '</adaptive-icon>', ''].join('\n');
}

// ---- rendering -----------------------------------------------------------------------------
const PNG = { compressionLevel: 9, adaptiveFiltering: false, palette: false };

// Renders the visible adaptive region (viewBox 18 18 72 72) at size x size; round masks to a full circle.
export async function renderPng(svgText, size, round) {
  const cropped = svgText
    .replace(/viewBox="[^"]*"/, 'viewBox="18 18 72 72"')
    .replace(/(<svg[^>]*?)\swidth="[^"]*"/, `$1 width="${size}"`)
    .replace(/(<svg[^>]*?)\sheight="[^"]*"/, `$1 height="${size}"`);
  let image = sharp(Buffer.from(cropped), { density: 72 }).ensureAlpha();
  if (round) {
    const mask = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"><circle cx="${size / 2}" cy="${size / 2}" r="${size / 2}" fill="#000000"/></svg>`);
    image = sharp(await image.png().toBuffer()).composite([{ input: mask, blend: 'dest-in' }]);
  }
  return image.png(PNG).toBuffer();
}

// ---- outputs and drift ---------------------------------------------------------------------
function pngTargets() {
  const list = Object.entries(DENSITIES).flatMap(([d, size]) => [[`${RES}/mipmap-${d}/ic_launcher.png`, size, false], [`${RES}/mipmap-${d}/ic_launcher_round.png`, size, true]]);
  return [...list, ['src/android/icons/play-store-512.png', 512, false]];
}

export async function generate(svgText) {
  const p = parseSvg(svgText);
  const text = (path, content) => ({ path, bytes: Buffer.from(content, 'utf8') });
  const xml = [
    text(`${RES}/drawable/ic_launcher_background.xml`, toVectorDrawable([p.background])),
    text(`${RES}/drawable/ic_launcher_foreground.xml`, toVectorDrawable([p.ring, p.iris, p.pupil, p.highlight])),
    text(`${RES}/drawable/ic_launcher_monochrome.xml`, toVectorDrawable(monochromeShapes(p))),
    ...['ic_launcher', 'ic_launcher_round'].flatMap(n => [text(`${RES}/mipmap-anydpi-v26/${n}.xml`, adaptiveXml(false)), text(`${RES}/mipmap-anydpi-v33/${n}.xml`, adaptiveXml(true))]),
  ];
  const png = await Promise.all(pngTargets().map(async ([path, size, round]) => ({ path, bytes: await renderPng(svgText, size, round) })));
  return [...xml, ...png];
}

export async function readSvg(root) { return readFile(join(root, SVG_PATH), 'utf8'); }

async function pixelsDiffer(a, b) {
  const [x, y] = await Promise.all([a, b].map(buf => sharp(buf).raw().toBuffer({ resolveWithObject: true })));
  if (x.info.width !== y.info.width || x.info.height !== y.info.height || x.info.channels !== y.info.channels) return 'dimensions differ';
  for (let i = 0; i < x.data.length; i++) if (Math.abs(x.data[i] - y.data[i]) > 2) return 'pixels differ';
  return null;
}

// Returns [{path, reason}] for every output that is missing or drifted (XML exact; PNG within 2 per channel).
export async function compareOutputs(root, outputs) {
  const drift = [];
  for (const { path, bytes } of outputs) {
    let disk;
    try { disk = await readFile(join(root, path)); } catch { drift.push({ path, reason: 'missing' }); continue; }
    if (path.endsWith('.png')) {
      const reason = await pixelsDiffer(disk, bytes).catch(() => 'unreadable PNG');
      if (reason) drift.push({ path, reason });
    } else if (!disk.equals(bytes)) drift.push({ path, reason: 'content differs' });
  }
  return drift;
}

// ---- safe-zone geometry --------------------------------------------------------------------
// Sample points of a path: cubics flattened; arcs must be semicircles and are sampled as full circles.
export function samplePoints(d) {
  const tokens = d.match(/[MmLlHhVvCcAaZz]|-?\d*\.?\d+(?:e[-+]?\d+)?/gi);
  const pts = [];
  let i = 0, cmd, x = 0, y = 0, sx = 0, sy = 0;
  const num = () => Number(tokens[i++]);
  while (i < tokens.length) {
    if (/[A-Za-z]/.test(tokens[i])) cmd = tokens[i++];
    if (cmd === 'Z' || cmd === 'z') { x = sx; y = sy; continue; }
    if (cmd === 'M') { x = num(); y = num(); sx = x; sy = y; pts.push([x, y]); cmd = 'L'; }
    else if (cmd === 'L') { x = num(); y = num(); pts.push([x, y]); }
    else if (cmd === 'H') { x = num(); pts.push([x, y]); }
    else if (cmd === 'V') { y = num(); pts.push([x, y]); }
    else if (cmd === 'C') {
      const [x1, y1, x2, y2, x3, y3] = [num(), num(), num(), num(), num(), num()];
      for (let t = 0; t <= 1.0001; t += 0.02) {
        const u = 1 - t, a = u ** 3, b = 3 * u * u * t, c = 3 * u * t * t, e = t ** 3;
        pts.push([a * x + b * x1 + c * x2 + e * x3, a * y + b * y1 + c * y2 + e * y3]);
      }
      x = x3; y = y3;
    } else if (cmd === 'A') {
      const [r, ry, , , , nx, ny] = [num(), num(), num(), num(), num(), num(), num()];
      if (r !== ry || Math.abs(Math.hypot(nx - x, ny - y) - 2 * r) > 1e-6) throw new Error('Only semicircle arcs are supported');
      const cx = (x + nx) / 2, cy = (y + ny) / 2;
      for (let k = 0; k < 360; k += 5) pts.push([cx + r * Math.cos(k * Math.PI / 180), cy + r * Math.sin(k * Math.PI / 180)]);
      x = nx; y = ny;
    } else throw new Error(`Unsupported path command ${cmd} in safe-zone check`);
  }
  return pts;
}
