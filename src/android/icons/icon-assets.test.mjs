import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { SAFE_CENTER, SAFE_RADIUS, compareOutputs, generate, parseSvg, samplePoints } from './icon-assets.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');
const svg = readFileSync(join(here, 'agent-eye.svg'), 'utf8');
const outputs = await generate(svg);
const byPath = Object.fromEntries(outputs.map(o => [o.path, o.bytes]));
const R = 'android/app/src/main/res';

test('regeneration is deterministic', async () => {
  const again = await generate(svg);
  assert.deepEqual(again.map(o => o.path), outputs.map(o => o.path));
  again.forEach((o, i) => assert.ok(o.bytes.equals(outputs[i].bytes), o.path));
});

test('output list covers every resource variant', () => {
  const expected = [
    ...['background', 'foreground', 'monochrome'].map(n => `${R}/drawable/ic_launcher_${n}.xml`),
    ...['v26', 'v33'].flatMap(v => ['ic_launcher', 'ic_launcher_round'].map(n => `${R}/mipmap-anydpi-${v}/${n}.xml`)),
    ...['mdpi', 'hdpi', 'xhdpi', 'xxhdpi', 'xxxhdpi'].flatMap(d => ['ic_launcher', 'ic_launcher_round'].map(n => `${R}/mipmap-${d}/${n}.png`)),
    'src/android/icons/play-store-512.png',
  ];
  assert.deepEqual(outputs.map(o => o.path).sort(), expected.sort());
});

test('XML resources are marked generated, LF-only, and monochrome only in v33', () => {
  for (const o of outputs.filter(o => o.path.endsWith('.xml'))) {
    const text = o.bytes.toString();
    assert.ok(text.startsWith('<!-- Generated by src/android/icons/generate-icons.mjs'), o.path);
    assert.ok(text.endsWith('>\n') && !text.includes('\r'), o.path);
  }
  assert.ok(!byPath[`${R}/mipmap-anydpi-v26/ic_launcher.xml`].toString().includes('monochrome'));
  assert.ok(byPath[`${R}/mipmap-anydpi-v33/ic_launcher_round.xml`].toString().includes('<monochrome android:drawable="@drawable/ic_launcher_monochrome"/>'));
  assert.match(byPath[`${R}/drawable/ic_launcher_monochrome.xml`].toString(), /evenOdd/);
});

test('PNG sizes, channels and alpha', async () => {
  const sizes = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
  for (const [density, size] of Object.entries(sizes)) {
    for (const name of ['ic_launcher', 'ic_launcher_round']) {
      const { data, info } = await sharp(byPath[`${R}/mipmap-${density}/${name}.png`]).raw().toBuffer({ resolveWithObject: true });
      assert.deepEqual([info.width, info.height, info.channels], [size, size, 4], `${density}/${name}`);
      assert.equal(data[3], name.endsWith('round') ? 0 : 255, `${density}/${name} corner alpha`);
    }
  }
  const { data, info } = await sharp(byPath['src/android/icons/play-store-512.png']).raw().toBuffer({ resolveWithObject: true });
  assert.deepEqual([info.width, info.height, info.channels], [512, 512, 4]);
  for (let i = 3; i < data.length; i += 4) if (data[i] !== 255) assert.fail('play asset not fully opaque');
});

test('foreground geometry stays inside the adaptive safe circle', () => {
  const p = parseSvg(svg);
  for (const id of ['ring', 'iris', 'pupil', 'highlight']) {
    for (const [x, y] of samplePoints(p[id].d)) {
      const dist = Math.hypot(x - SAFE_CENTER[0], y - SAFE_CENTER[1]);
      assert.ok(dist <= SAFE_RADIUS, `${id} point (${x}, ${y}) is ${dist} from centre`);
    }
  }
});

test('rejects unsupported SVG', () => {
  const path = '<path id="background" d="M0,0H108V108H0Z" fill="#101B2D" fill-rule="nonzero"/>';
  const wrap = inner => `<svg xmlns="http://www.w3.org/2000/svg" width="108" height="108" viewBox="0 0 108 108">${inner}</svg>`;
  const cases = {
    group: wrap(`<g>${path}</g>`),
    circle: wrap('<circle cx="1" cy="1" r="1"/>'),
    transform: wrap(path.replace('<path', '<path transform="scale(2)"')),
    href: wrap(path.replace('<path', '<path xlink:href="http://x/y"')),
    urlFill: wrap(path.replace('fill="#101B2D"', 'fill="url(#g)"')),
    text: wrap('<text>Hi</text>'),
    stroke: wrap(path.replace('<path', '<path stroke="#000000"')),
    viewBox: wrap(path).replace('0 0 108 108', '0 0 100 100'),
  };
  for (const [name, source] of Object.entries(cases)) assert.throws(() => parseSvg(source), /Unsupported|must be/, name);
});

test('compareOutputs flags missing, modified XML and modified PNG', async () => {
  mkdirSync(join(root, '.tmp'), { recursive: true });
  const dir = mkdtempSync(join(root, '.tmp', 'icons-test-'));
  try {
    for (const o of outputs) { mkdirSync(dirname(join(dir, o.path)), { recursive: true }); writeFileSync(join(dir, o.path), o.bytes); }
    assert.deepEqual(await compareOutputs(dir, outputs), []);
    const xml = `${R}/drawable/ic_launcher_background.xml`;
    const png = `${R}/mipmap-mdpi/ic_launcher.png`;
    const gone = `${R}/mipmap-hdpi/ic_launcher.png`;
    writeFileSync(join(dir, xml), 'changed');
    writeFileSync(join(dir, png), await sharp(byPath[png]).negate({ alpha: false }).png().toBuffer());
    rmSync(join(dir, gone));
    const drift = (await compareOutputs(dir, outputs)).map(d => d.path).sort();
    assert.deepEqual(drift, [xml, png, gone].sort());
  } finally { rmSync(dir, { recursive: true, force: true }); }
});
